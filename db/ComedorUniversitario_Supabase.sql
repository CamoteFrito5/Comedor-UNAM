-- 4.1 TABLA SOLICITUD (Reservas diarias de alimentación de beneficiarios)
CREATE TABLE public.solicitud (
    id_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_solicitud DATE NOT NULL DEFAULT CURRENT_DATE,
    id_beneficiario INTEGER NOT NULL,
    id_tipo_racion INTEGER NOT NULL,
    id_horario INTEGER NOT NULL,
    id_estado_solicitud INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT fk_solicitud_beneficiario FOREIGN KEY (id_beneficiario) REFERENCES public.beneficiario(id_beneficiario) ON DELETE CASCADE,
    CONSTRAINT fk_solicitud_tipo_racion FOREIGN KEY (id_tipo_racion) REFERENCES public.tipo_racion(id_tipo_racion) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_horario FOREIGN KEY (id_horario) REFERENCES public.horario(id_horario) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_estado_solicitud FOREIGN KEY (id_estado_solicitud) REFERENCES public.estado_solicitud(id_estado_solicitud) ON DELETE RESTRICT
);

-- 4.2 TABLA DETALLE SOLICITUD
CREATE TABLE public.detalle_solicitud (
    id_detalle_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud INTEGER NOT NULL,
    observacion VARCHAR(250),
    fecha_atencion TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_detalle_solicitud_solicitud FOREIGN KEY (id_solicitud) REFERENCES public.solicitud(id_solicitud) ON DELETE CASCADE
);

-- 4.3 TABLA ASISTENCIA (Control transaccional diario)
CREATE TABLE public.asistencia (
    id_asistencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud INTEGER NOT NULL,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    hora TIME NOT NULL DEFAULT CURRENT_TIME,
    asistio BOOLEAN NOT NULL DEFAULT FALSE,
    justificado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_asistencia_solicitud FOREIGN KEY (id_solicitud) REFERENCES public.solicitud(id_solicitud) ON DELETE CASCADE
);


